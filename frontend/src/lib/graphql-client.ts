import type { ErrorCode, FieldError } from "@template/shared";

import { GRAPHQL_ENDPOINT } from "@/config";
import type { TypedDocumentString } from "@/gql/graphql";

/** Thrown when the API answers with `errors`. Branch on `code`; show `details` next to form fields. */
export class GraphQLRequestError extends Error {
  constructor(
    readonly code: ErrorCode | "NETWORK_ERROR" | "GRAPHQL_VALIDATION_FAILED",
    message: string,
    readonly details?: FieldError[],
  ) {
    super(message);
    this.name = "GraphQLRequestError";
  }
}

type GraphQLResponse<T> = {
  data?: T | null;
  errors?: { message: string; extensions?: { code?: string; details?: FieldError[] } }[];
};

// Every generated document starts with "query Name" or "mutation Name".
function operationName(query: string): string | undefined {
  return /^\s*(?:query|mutation)\s+(\w+)/.exec(query)?.[1];
}

/**
 * Typed GraphQL call. The result and variable types come from the document itself
 * (generated by `npm run codegen`), so there is nothing to annotate at the call site.
 * Throws GraphQLRequestError if the server returned `errors`.
 */
export async function gqlRequest<TResult, TVariables>(
  document: TypedDocumentString<TResult, TVariables>,
  ...[variables]: TVariables extends Record<string, never> ? [] : [TVariables]
): Promise<TResult> {
  const query = document.toString();
  let res: Response;
  try {
    res = await fetch(GRAPHQL_ENDPOINT, {
      method: "POST",
      credentials: "same-origin",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({ query, variables, operationName: operationName(query) }),
    });
  } catch {
    throw new GraphQLRequestError("NETWORK_ERROR", "Can't reach the server. Please try again.");
  }

  const body = (await res.json().catch(() => null)) as GraphQLResponse<TResult> | null;
  const first = body?.errors?.[0];
  if (first) {
    const code = (first.extensions?.code ?? "INTERNAL_ERROR") as ErrorCode;
    throw new GraphQLRequestError(code, first.message, first.extensions?.details);
  }
  if (!body?.data) {
    throw new GraphQLRequestError("INTERNAL_ERROR", "Something went wrong. Please try again.");
  }
  return body.data;
}
